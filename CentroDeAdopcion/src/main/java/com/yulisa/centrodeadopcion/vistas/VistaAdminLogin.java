            JOptionPane.showMessageDialog(this, "BIENVENIDO AL SISTEMA DE ADMINISTRADOR", "LOGIN EXITOSO", JOptionPane.INFORMATION_MESSAGE);
            VistaAdmin vista_a = new VistaAdmin();
