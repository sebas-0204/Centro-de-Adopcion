    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        // TODO add your handling code here:
        try {
            String nombre = txtName.getText().trim();
            int edad = Integer.parseInt(txtEdad.getText().trim());
            String raza = txtRaza.getText().trim();
            String fechaDeIngreso = txtIngreso.getText().trim();
            String descripcion = txtDescripcion.getText();

            boolean estadoDeAdopcion = cmbAdopt.getSelectedItem().toString().equalsIgnoreCase("Sí");
            String tipoSeleccionado = cmbTipoAnimal.getSelectedItem().toString();
            if (nombre.isEmpty() || raza.isEmpty() || fechaDeIngreso.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, completa todos los campos de texto.",
                    "Campos vacíos",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

        Animal nuevoAnimal;
        
        if (tipoSeleccionado.equalsIgnoreCase("Perro")) {
            nuevoAnimal = new Perro(nombre, edad,fechaDeIngreso, raza,estadoDeAdopcion, descripcion);
        } else {
            nuevoAnimal = new Gato(nombre, edad, fechaDeIngreso, raza,estadoDeAdopcion, descripcion);
        }

        ControladorAnimales.agregarAnimal(nuevoAnimal);

        javax.swing.JOptionPane.showMessageDialog(this, 
            "¡" + tipoSeleccionado + " registrado con éxito!", 
            "Éxito", 
            javax.swing.JOptionPane.INFORMATION_MESSAGE);
        VistaAdmin volver = new VistaAdmin();
        volver.setVisible(true);
        this.dispose();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Por favor, ingresa un número válido en el campo de Edad.",
                "Error de formato",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnFinalizarActionPerformed

