    public VistaAnimales() {
        initComponents();
        this.setLocationRelativeTo(this);
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
        new Object[]{"Nombre", "Edad", "Tipo","Adoptado"},0);
    
    
        for (Animal a : ControladorAnimales.getListaAnimales()) {
            String tipo = "Animal";
            String adoptado ="";
            if (a instanceof Perro) {
                tipo = "Perro";
            } else if (a instanceof Gato) {
            tipo = "Gato";
            }
            
            if (a.isEstadoDeAdopcion()){
                adoptado = "SÍ";
            } else{
                adoptado = "NO";
            }
            Object[] fila = { a.getNombre(), a.getEdad(), tipo, adoptado };
            modelo.addRow(fila); 
        }
    
    
        tblAnimals.setModel(modelo);
    }

