    private void btnSignUpActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSignUpActionPerformed
        // TODO add your handling code here:
        String userTemp = txtUser.getText();
        String passTemp = txtPassword.getText();
      
        if (userTemp.isEmpty() || passTemp.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, complete todos los campos.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
        
        boolean yaExiste = false;

        for (Cliente c : ControladorClientes.getListaClientes()) {
            if (c.getUsuario().equalsIgnoreCase(userTemp)) {
            yaExiste = true;
            break;
            }
        }

        if (yaExiste) {
            javax.swing.JOptionPane.showMessageDialog(this, "El nombre de usuario ya está registrado. Elija otro.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        } else {
            VistaFormularioInscripcion ventanaInscripcion = new VistaFormularioInscripcion(userTemp, passTemp);
            ventanaInscripcion.setVisible(true);
            this.dispose();
    }//GEN-LAST:event_btnSignUpActionPerformed
    }       
