    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        // TODO add your handling code here:
        try {

            String nombre = txtName.getText().trim();
            int edad = Integer.parseInt(txtEdad.getText().trim());
            String contacto = txtContact.getText().trim();
            String documento = txtId.getText().trim();
            String cargo = txtCargo.getText().trim();

            if (nombre.isEmpty() || contacto.isEmpty() || documento.isEmpty() || cargo.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this,
                    "Por favor, completa todos los campos de texto.",
                    "Campos vacíos",
                    javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            Trabajador nuevoTrabajador = new Trabajador(
                nombre,
                edad,
                documento,
                contacto,
                cargo
            );

            ControladorTrabajadores.agregarTrabajador(nuevoTrabajador);

            javax.swing.JOptionPane.showMessageDialog(this, "¡Registro del empleado con éxito!",  "Éxito",  javax.swing.JOptionPane.INFORMATION_MESSAGE);
            VistaAdmin vista_c = new VistaAdmin();
            vista_c.setVisible(true);
            this.dispose();

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this,
                "Por favor, ingresa un número válido en el campo de Edad.",
                "Error de formato",
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnFinalizarActionPerformed

