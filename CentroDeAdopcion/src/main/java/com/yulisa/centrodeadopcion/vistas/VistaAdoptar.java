    private void cargarTabla(){
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel(
        new Object[]{"Nombre", "Edad", "Raza", "Tipo"},0
    );
        for (Animal a : ControladorAnimales.getListaAnimales()) {
            String tipo = "Animal";
            if (a.isEstadoDeAdopcion()==false){
                if (a instanceof Perro) {
                    tipo = "Perro";
                    } else if (a instanceof Gato) {
                        tipo = "Gato";
                    }
        
                Object[] fila = { a.getNombre(), a.getEdad(),a.getRaza(), tipo };
                modelo.addRow(fila); 
            }
        }   
    
        tblAdopt.setModel(modelo);
    }

