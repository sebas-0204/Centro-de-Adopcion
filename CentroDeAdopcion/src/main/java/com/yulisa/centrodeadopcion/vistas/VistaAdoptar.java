    private void btnAdoptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdoptActionPerformed
        // TODO add your handling code here:
        int filaSeleccionada = tblAdopt.getSelectedRow();

        if (filaSeleccionada == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, seleccione un animal de la tabla.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String nombreAnimal = tblAdopt.getValueAt(filaSeleccionada, 0).toString();

        javax.swing.JOptionPane.showMessageDialog(this, "¡Felicitaciones! Has adoptado a " + nombreAnimal + " con éxito.");
         for (Animal a : ControladorAnimales.getListaAnimales()) {
            if (a.getNombre().equalsIgnoreCase(nombreAnimal)) {
                a.setEstadoDeAdopcion(true); 
                break;
            }
        }
        
        ControladorAnimales.guardarDatos(); 
        cargarTabla();
    }//GEN-LAST:event_btnAdoptActionPerformed

