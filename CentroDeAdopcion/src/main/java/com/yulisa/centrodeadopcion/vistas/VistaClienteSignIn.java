    private void btnSingInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSingInActionPerformed
        if (!txtUser.getText().equalsIgnoreCase("") && !txtPassword.getText().equalsIgnoreCase("")){
            String userIngresado = txtUser.getText().trim();
            String passIngresado = txtPassword.getText().trim();
    
            boolean usuarioEncontrado = false;
            
            for (Cliente c : ControladorClientes.getListaClientes()) {

                if (c.getUsuario().equals(userIngresado) && c.getPassword().equals(passIngresado)) {
                usuarioEncontrado = true;
                break; 
                }
            }   
            if (usuarioEncontrado==true){
                SesionActual.tipoUsuario = "Cliente";
                JOptionPane.showMessageDialog(this, "BIENVENIDO AL SISTEMA", "Login Exitoso", JOptionPane.INFORMATION_MESSAGE);
                VistaCliente vista_c = new VistaCliente();
                vista_c.setVisible(true);
                this.dispose();
            }
        
        }else{
            JOptionPane.showMessageDialog(this, "Ingrese un usuario y contraseña válidos", "Error Login", JOptionPane.ERROR_MESSAGE);
            txtUser.setText("");
            txtPassword.setText("");
        }
    }//GEN-LAST:event_btnSingInActionPerformed

