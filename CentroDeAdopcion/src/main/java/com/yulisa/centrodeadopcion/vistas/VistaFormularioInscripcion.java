    private void btnFinalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFinalizarActionPerformed
        // TODO add your handling code here:
        try {
        
        String nombre = txtName.getText().trim();
        int edad = Integer.parseInt(txtEdad.getText().trim());
        String contacto = txtContact.getText().trim();
        String documento = txtId.getText().trim();

        boolean ingresos = cmbIngresos.getSelectedItem().toString().equalsIgnoreCase("Sí");
        boolean espacioVivienda = cmbVivienda.getSelectedItem().toString().equalsIgnoreCase("Sí");
        boolean mascotasAntes = cmbMascotas.getSelectedItem().toString().equalsIgnoreCase("Sí");

        if (nombre.isEmpty() || contacto.isEmpty() || documento.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                "Por favor, completa todos los campos de texto.", 
                "Campos vacíos", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

 
        Cliente nuevoCliente = new Cliente(
            nombre, 
            edad, 
            documento, 
            contacto, 
            ingresos, 
            espacioVivienda, 
            mascotasAntes, 
            user,  
            pass   
        );

        ControladorClientes.agregarCliente(nuevoCliente);

        javax.swing.JOptionPane.showMessageDialog(this, "¡Registro de adopción completado con éxito!",  "Éxito",  javax.swing.JOptionPane.INFORMATION_MESSAGE);  
        VistaClienteSignIn vista_c = new VistaClienteSignIn();
        vista_c.setVisible(true);
        this.dispose();

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Por favor, ingresa un número válido en el campo de Edad.", 
            "Error de formato", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnFinalizarActionPerformed

